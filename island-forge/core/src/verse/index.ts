function reloadCutoffSeconds(spec: MapSpec): number {
  const cutoff = spec.rules.respawn_cutoff_phase;
  if (!spec.rules.respawn_enabled) return 0;
  if (!cutoff) return spec.rules.round_time_s;
  return spec.storm.phases.slice(0, Math.max(0, cutoff - 1)).reduce((t, p) => t + p.wait_s + p.shrink_s, 0) + (spec.storm.phases[cutoff - 1]?.wait_s || 0);
}

