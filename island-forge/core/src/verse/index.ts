export interface Marker {
  label: string;
  category: string;
  X: number;
  Y: number;
  Z: number;
  grid: string;
}

export function collectMarkers(spec: MapSpec): Marker[] {
  const markers: Marker[] = [];
  for (const p of spec.pois) markers.push({ label: p.name, category: 'poi', ...toWorld(spec, p.x, p.y, p.elevation), grid: gridRef(p.x, p.y) });
  for (const f of spec.features) {
    const label = [featureStyle(f.type).label, f.order ? `#${f.order}` : '', f.team ? `team ${f.team}` : ''].filter(Boolean).join(' ');
    markers.push({ label, category: f.type, ...toWorld(spec, f.x, f.y), grid: gridRef(f.x, f.y) });
  }
  if (spec.bus_route) {
    markers.push({ label: 'Bus Start', category: 'route', ...toWorld(spec, spec.bus_route.start.x, spec.bus_route.start.y), grid: gridRef(spec.bus_route.start.x, spec.bus_route.start.y) });
    markers.push({ label: 'Bus End', category: 'route', ...toWorld(spec, spec.bus_route.end.x, spec.bus_route.end.y), grid: gridRef(spec.bus_route.end.x, spec.bus_route.end.y) });
  }
  if (spec.storm.phases.length) {
    markers.push({ label: 'Final Circle', category: 'route', ...toWorld(spec, spec.storm.final_x, spec.storm.final_y), grid: gridRef(spec.storm.final_x, spec.storm.final_y) });
  }
  return markers;
}

