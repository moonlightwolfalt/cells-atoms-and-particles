// Verse code library. Each module turns a map spec into one .verse file containing one
// creative_device, plus the wiring steps a creator follows in UEFN.
//
// The code sticks to long-standing Fortnite Verse APIs (creative devices, fort_character
// elimination events, team collection, SpawnProp, the UI widgets). It is generated, not
// compiled here; if a UEFN update renames something, the Verse compiler points at the line.
import type { MapSpec } from '../types.ts';
import { MODES } from '../modes.ts';
import { toWorld, stormCenters, gridRef } from '../terrain.ts';
import { featureStyle } from '../features.ts';

export interface VerseModule {
  id: string;
  title: string;
  description: string;
  fileName: (spec: MapSpec) => string;
  deviceName: (spec: MapSpec) => string;
  generate: (spec: MapSpec) => string;
  /** Steps to wire the device in UEFN after building Verse code. */
  setup: (spec: MapSpec) => string[];
}

export function verseIdent(name: string): string {
  const id = String(name)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 24)
    .replace(/_+$/, '');
  return /^[a-z]/.test(id) ? id : `island_${id || 'map'}`;
}

export const verseString = (s: string) => `"${String(s).replace(/[\\"{}<>]/g, '').replace(/\s+/g, ' ')}"`;
export const verseFloat = (n: number) => (Number.isInteger(n) ? `${n}.0` : String(Math.round(n * 1000) / 1000));

const deviceName = (spec: MapSpec, id: string) => `${verseIdent(spec.name)}_${id}_device`;
const header = (spec: MapSpec, title: string, lines: string[]) =>
  [
    `# ${title} — generated by Island Forge for "${spec.name.replace(/"/g, '')}" (${MODES[spec.mode]?.label || spec.mode}).`,
    ...lines.map((l) => `# ${l}`),
    '',
  ].join('\n');

const WATCH_ELIMINATIONS = `
    var WatchedPlayers : [player]logic = map{}

    # Subscribes to every player's elimination event, including players who join late.
    WatchEliminations()<suspends> : void =
        loop:
            for (Player : GetPlayspace().GetPlayers(), not WatchedPlayers[Player]?, Character := Player.GetFortCharacter[]):
                Character.EliminatedEvent().Subscribe(OnEliminated)
                if (set WatchedPlayers[Player] = true) {}
            Sleep(1.0)`;

const MSG = (spec: MapSpec, mod: string) => `${verseIdent(spec.name)}_${mod}_msg`;
const msgFn = (spec: MapSpec, mod: string) => `${MSG(spec, mod)}<localizes>(Text : string) : message = "{Text}"\n`;

