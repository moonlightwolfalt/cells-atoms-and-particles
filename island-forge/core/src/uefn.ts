export function slug(spec: MapSpec): string {
  return verseIdent(spec.name).replace(/_/g, '-');
}

/** All files of the UEFN package. Pass rendered images from a browser if you have them. */
export async function packageFiles(spec: MapSpec, images: { thumbnailJpg?: Uint8Array; minimapPng?: Uint8Array } = {}): Promise<ZipEntry[]> {
  const folder = `${slug(spec)}-uefn`;
  const files: ZipEntry[] = [
    { name: `${folder}/README.md`, data: generateReadme(spec) },
    { name: `${folder}/map-spec.json`, data: JSON.stringify(spec, null, 2) },
    { name: `${folder}/devices.csv`, data: devicesCsv(spec) },
    { name: `${folder}/builds.csv`, data: buildsCsv(spec) },
    { name: `${folder}/publish.txt`, data: publishKit(spec) },
    { name: `${folder}/heightmap-1009.png`, data: await heightmapPng(spec, 1009) },
    { name: `${folder}/biome-paint.png`, data: await biomePaintPng(spec, 512) },
  ];
  for (const v of generateVerseFiles(spec)) files.push({ name: `${folder}/Verse/${v.path}`, data: v.code });
  if (images.thumbnailJpg) files.push({ name: `${folder}/thumbnail.jpg`, data: images.thumbnailJpg });
  if (images.minimapPng) files.push({ name: `${folder}/minimap.png`, data: images.minimapPng });
  return files;
}

export async function buildPackageZip(spec: MapSpec, images: { thumbnailJpg?: Uint8Array; minimapPng?: Uint8Array } = {}): Promise<Uint8Array> {
  return createZip(await packageFiles(spec, images));
}
